/// <summary>
/// Character-width tables (in 1/1000 em units, i.e. AFM convention) for the four non-monospace
/// standard-14 fonts this library uses: Helvetica, Helvetica-Bold, Times-Roman and Times-Bold.
/// These are the genuine Adobe Core-14 AFM glyph metrics, addressed by the actual Unicode character
/// that WinAnsiEncoding (~= cp1252 / Latin-1) maps each 0x20-0xFF code point to. Because Latin-1
/// Supplement (U+00A0-U+00FF) is numerically identical to cp1252 at those same positions, indexing
/// by the real character (rather than by a raw byte) covers the whole 0x20-0xFF WinAnsi range and,
/// as a bonus, also covers the handful of cp1252 0x80-0x9F "special" glyphs (curly quotes, dashes,
/// ellipsis, Euro sign, etc.) via their real Unicode code points (e.g. U+2014 em dash), which is what
/// actually shows up in .NET strings - the raw C1-control-range code points 0x80-0x9F themselves
/// never appear in real text and are not meaningfully distinct glyphs.
///
/// Values are the public, standard Adobe Core-14 AFM widths (the same numbers reproduced identically
/// in every PDF library's AFM resources - PDFBox, iText, ghostscript, matplotlib, pdf.js, etc.) - this
/// is specification data, not copyrighted creative expression. Accented Latin letters share the
/// advance width of their unaccented base letter, which is how these fonts are actually constructed
/// (Aacute has the same width as A, eacute the same as e, and so on) - a reliable, well-established
/// pattern used throughout the tables below.
/// </summary>
public static class AfmWidths
{
    public static int GetWidth1000(PdfStandardFont font, char c)
    {
        if (font is PdfStandardFont.Courier or PdfStandardFont.CourierBold) return 600;

        return font switch
        {
            PdfStandardFont.Helvetica => Helvetica(c),
            PdfStandardFont.HelveticaBold => HelveticaBold(c),
            PdfStandardFont.TimesRoman => TimesRoman(c),
            PdfStandardFont.TimesBold => TimesBold(c),
            _ => 556,
        };
    }

    public static double MeasureWidthPt(PdfStandardFont font, string text, double sizePt)
    {
        if (string.IsNullOrEmpty(text)) return 0;
        int total = 0;
        foreach (var c in text) total += GetWidth1000(font, c);
        return total / 1000.0 * sizePt;
    }

